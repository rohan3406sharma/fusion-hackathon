"""Turn the narration plan + measured voice durations into the master timeline.

Inputs : scripts/narration.json, assets/voice/manifest.json (from scripts/tts.py),
         assets/voice/words.json (optional, from `npx hyperframes transcribe`)
Outputs: assets/timeline.json   absolute start/end of every scene and line (+ words when available)
         assets/timeline.js     the same object as `window.TL`, loaded by every composition
         assets/voice/narration.wav   all lines placed at their start times (48 kHz mono)

Run: .venv-tts/bin/python scripts/build_timeline.py
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import soundfile as sf

ROOT = Path(__file__).resolve().parent.parent
SR = 48000
XFADE = 0.5   # each scene slot starts this much before its narration window, to cross-fade over the previous one


def resample(x: np.ndarray, sr_in: int, sr_out: int) -> np.ndarray:
    if sr_in == sr_out:
        return x
    n = int(round(len(x) * sr_out / sr_in))
    t_in = np.arange(len(x)) / sr_in
    t_out = np.arange(n) / sr_out
    return np.interp(t_out, t_in, x).astype(np.float32)


def _norm(w: str) -> str:
    s = "".join(ch for ch in w.lower() if ch.isalnum() or ch in "%$.")
    return s[:-1] if s.endswith(".") else s


def resolve_cues(tl: dict) -> None:
    """Resolve scripts/cues.json anchors to absolute seconds: tl['cues'], tl['rec'], tl['sfx']."""
    spec = json.loads((ROOT / "scripts" / "cues.json").read_text())
    cap = json.loads((ROOT / "captures" / "manifest.json").read_text())
    sc = {s["id"]: s for s in tl["scenes"]}
    ln = {l["id"]: l for s in tl["scenes"] for l in s["lines"]}
    cues: dict[str, float] = {}
    recs: dict[str, dict] = {}

    def at(a: dict) -> float:
        off = a.get("offset", 0.0)
        if "cue" in a:
            return cues[a["cue"]] + off
        if "rec" in a:
            r = recs[a["rec"]]
            ev = next(e["t"] for e in cap["recordings"][a["rec"]]["events"] if e["label"] == a["event"])
            return r["abs0"] + ev + off
        if "scene" in a:
            s = sc[a["scene"]]
            edge = a.get("edge", "start")
            return {"end": s["end"], "slot": s["slot_start"]}.get(edge, s["start"]) + off
        line = ln[a["line"]]
        if "word" in a:
            want, n, k = _norm(a["word"]), a.get("n", 0), 0
            for w in line["words"]:
                if _norm(w["w"]).startswith(want):
                    if k == n:
                        return (w["e"] if a.get("edge") == "e" else w["s"]) + off
                    k += 1
            raise SystemExit(f"word {a['word']!r} not in {a['line']}: {[w['w'] for w in line['words']]}")
        return (line["end"] if a.get("edge") == "end" else line["start"]) + off

    for name, r in spec["rec"].items():
        meta = cap["recordings"][name]
        ev = next(e["t"] for e in meta["events"] if e["label"] == r["event"])
        abs0 = at(r["align"]) - ev
        vis0, vis1 = at(r["from"]), at(r["to"])
        vis0 = max(vis0, abs0)                      # cannot show media before its first frame
        vis1 = min(vis1, abs0 + meta["duration"] - 0.05)
        s0 = sc[r["scene"]]["slot_start"]
        recs[name] = {"abs0": round(abs0, 3), "start": round(vis0, 3), "end": round(vis1, 3), "local": round(vis0 - s0, 3),
                      "duration": round(vis1 - vis0, 3), "mediaStart": round(vis0 - abs0, 3), "file": meta["file"],
                      "events": {e["label"]: round(abs0 + e["t"], 3) for e in meta["events"]}}
    for name, a in spec["cues"].items():
        cues[name] = round(at(a), 3)
    tl["cues"], tl["rec"] = cues, recs
    tl["sfx"] = [{"file": f["file"], "t": round(at(f["at"]), 3), "db": f["db"]} for f in spec["sfx"]]
    (ROOT / "assets" / "data").mkdir(parents=True, exist_ok=True)
    (ROOT / "assets" / "data" / "captures.js").write_text(
        "// Generated by scripts/build_timeline.py from captures/manifest.json\nwindow.CAP = " + json.dumps(cap) + ";\n")


def main() -> None:
    spec = json.loads((ROOT / "scripts" / "narration.json").read_text())
    man = json.loads((ROOT / "assets" / "voice" / "manifest.json").read_text())
    words_path = ROOT / "assets" / "voice" / "words.json"
    words = json.loads(words_path.read_text()) if words_path.exists() else []

    t = 0.0
    scenes = []
    for s in spec["scenes"]:
        start = t
        t += s["lead_in"]
        lines = []
        for ln in s["lines"]:
            dur = man[ln["id"]]["duration"]
            item = {"id": ln["id"], "start": round(t, 3), "end": round(t + dur, 3), "say": ln["say"]}
            if "show" in ln:
                item["show"] = ln["show"]
            lines.append(item)
            t += dur + ln["gap"]
        scenes.append({"id": s["id"], "start": round(start, 3), "end": round(t, 3), "lines": lines})
    total = round(t, 3)

    # attach whisper word timings to the line they fall in
    for sc in scenes:
        for ln in sc["lines"]:
            ln["words"] = [
                {"w": w["text"], "s": round(w["start"], 3), "e": round(w["end"], 3)}
                for w in words
                if ln["start"] - 0.15 <= w["start"] < ln["end"] + 0.15
            ]

    for i, sc in enumerate(scenes):
        sc["slot_start"] = round(max(0.0, sc["start"] - (XFADE if i else 0.0)), 3)
        sc["slot_duration"] = round(sc["end"] - sc["slot_start"], 3)
    tl = {"fps": 30, "width": 1920, "height": 1080, "total": total, "xfade": XFADE, "scenes": scenes}
    resolve_cues(tl)
    (ROOT / "assets" / "timeline.json").write_text(json.dumps(tl, indent=1))
    (ROOT / "assets" / "data" / "timeline.js").write_text(
        "// Generated by scripts/build_timeline.py — do not edit by hand.\nwindow.TL = " + json.dumps(tl) + ";\n"
    )

    track = np.zeros(int(np.ceil(total * SR)) + SR, dtype=np.float32)
    for sc in scenes:
        for ln in sc["lines"]:
            x, sr = sf.read(ROOT / man[ln["id"]]["file"], dtype="float32")
            if x.ndim > 1:
                x = x.mean(axis=1)
            x = resample(x, sr, SR)
            i = int(round(ln["start"] * SR))
            track[i:i + len(x)] += x
    track = track[: int(np.ceil(total * SR))]
    sf.write(ROOT / "assets" / "voice" / "narration.wav", track, SR, subtype="PCM_16")

    for sc in scenes:
        print(f"{sc['id']:<16} {sc['start']:7.2f} → {sc['end']:7.2f}  ({sc['end'] - sc['start']:5.2f}s, {len(sc['lines'])} lines)")
    print(f"total {total:.2f}s  words attached: {sum(len(l['words']) for s in scenes for l in s['lines'])}")


if __name__ == "__main__":
    main()
