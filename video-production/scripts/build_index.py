"""Write index.html (the root composition) from assets/timeline.json.

Scene slots overlap by TL.xfade seconds so each scene can cross-fade in over the previous one.
Persistent layers: ink background with slow glows + faint survey grid, a static grain texture, and
the single pre-mixed audio track (assets/audio/mix.wav from scripts/mix.py).
Run: .venv-tts/bin/python scripts/build_index.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

TEMPLATE = """<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1920, height=1080" />
    <title>FIN-04 Climate Exposure Graph — explainer</title>
    <!-- Generated by scripts/build_index.py from assets/timeline.json. Edit the generator, not this file. -->
    <link rel="stylesheet" href="assets/css/base.css" />
    <script src="assets/vendor/gsap.min.js"></script>
    <script src="assets/data/timeline.js"></script>
    <script src="assets/data/captures.js"></script>
    <script src="assets/data/geo.js"></script>
    <script src="assets/js/fx.js"></script>
    <style>
      @font-face { font-family: "Instrument Serif"; src: url("assets/fonts/InstrumentSerif-400.woff2") format("woff2"); font-weight: 400; font-style: normal; }
      @font-face { font-family: "Instrument Serif"; src: url("assets/fonts/InstrumentSerif-400-italic.woff2") format("woff2"); font-weight: 400; font-style: italic; }
      @font-face { font-family: "Archivo Black"; src: url("assets/fonts/ArchivoBlack-400.woff2") format("woff2"); font-weight: 400; }
      @font-face { font-family: "Space Grotesk"; src: url("assets/fonts/SpaceGrotesk-500.woff2") format("woff2"); font-weight: 500; }
      @font-face { font-family: "Space Grotesk"; src: url("assets/fonts/SpaceGrotesk-700.woff2") format("woff2"); font-weight: 700; }
      @font-face { font-family: "Inter"; src: url("assets/fonts/Inter-400.woff2") format("woff2"); font-weight: 400; }
      @font-face { font-family: "Inter"; src: url("assets/fonts/Inter-700.woff2") format("woff2"); font-weight: 700; }
      @font-face { font-family: "JetBrains Mono"; src: url("assets/fonts/JetBrainsMono-400.woff2") format("woff2"); font-weight: 400; }
      #root { position: relative; width: 100%; height: 100%; overflow: hidden; background: #0c1016; }
      #root > div[data-composition-src] { position: absolute; inset: 0; }
      #grain { position: absolute; inset: 0; pointer-events: none; opacity: 0.045; mix-blend-mode: overlay; background-image: url("assets/img/grain.png"); background-size: 512px 512px; z-index: 50; }
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="root" data-start="0" data-width="1920" data-height="1080" data-duration="{total}">
      <div id="el-bg" data-composition-id="bg" data-composition-src="compositions/bg.html" data-start="0" data-duration="{total}" data-track-index="0" data-width="1920" data-height="1080"></div>
{slots}
      <div id="grain" class="clip" data-start="0" data-duration="{total}" data-track-index="30"></div>
      <audio id="mix" src="assets/audio/mix.wav" data-start="0" data-duration="{total}" data-track-index="40" data-volume="1"></audio>
    </div>
    <script>
      (function () {
        const tl = gsap.timeline({ paused: true });
        window.__timelines["root"] = tl;
      })();
    </script>
  </body>
</html>
"""


def main() -> None:
    tl = json.loads((ROOT / "assets" / "timeline.json").read_text())
    slots = []
    for i, s in enumerate(tl["scenes"]):
        slots.append(
            f'      <div id="el-{s["id"]}" data-composition-id="{s["id"]}" data-composition-src="compositions/{s["id"]}.html" '
            f'data-start="{s["slot_start"]}" data-duration="{s["slot_duration"]}" data-track-index="{1 + i % 2}" '
            f'data-width="1920" data-height="1080"></div>'
        )
    html = TEMPLATE.replace("{total}", str(tl["total"])).replace("{slots}", "\n".join(slots))
    (ROOT / "index.html").write_text(html)
    print("index.html:", len(tl["scenes"]), "scenes,", tl["total"], "s")


if __name__ == "__main__":
    main()
